const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const htmlPath = path.join(root, "index.html");
const cssPath = path.join(root, "styles.css");
const appPath = path.join(root, "app.js");
const outPath = path.join(root, "shell-single.generated.html");

const html = fs.readFileSync(htmlPath, "utf8");
const css = fs.readFileSync(cssPath, "utf8");
const app = fs.readFileSync(appPath, "utf8");
// Escape </script so embedded app does not close the host script tag.
const appEsc = app.replace(/<\/script/gi, "<\\/script");

const bootstrapHead = `
  <script>
    (function () {
      var resolveReady, rejectReady;
      window.__SNLAB_READY = new Promise(function (resolve, reject) {
        resolveReady = resolve;
        rejectReady = reject;
      });
      window.Module = window.Module || {};
      window.Module.noInitialRun = true;
      window.Module.onRuntimeInitialized = function () {
        try { resolveReady(window.Module); }
        catch (e) { rejectReady(e); }
      };
      window.Module.onAbort = function (reason) {
        rejectReady(reason instanceof Error ? reason : new Error(String(reason)));
      };
    })();
  </script>
  {{{ SCRIPT }}}
  <script>
`;
const bootstrapTail = `
  </script>`;

// Use function replacers so "$" / "$`" inside CSS/JS are NOT interpreted by String.replace.
let output = html.replace(
  /<link\s+rel="stylesheet"\s+href=".\/styles\.css"\s*\/?>/,
  () => "  <style>\n" + css + "\n  </style>"
);
output = output.replace(
  '  <script type="module" src="./app.js"></script>',
  () => bootstrapHead + appEsc + bootstrapTail
);

output = output.replace(
  "<title>SuperNumber Lab</title>",
  "<title>SuperNumber Lab (Single)</title>"
);

fs.writeFileSync(
  outPath,
  "<!-- Generated by webapp/tools/build-single-shell.js. Do not edit. -->\n" + output,
  "utf8"
);
console.log("generated", path.relative(process.cwd(), outPath));
